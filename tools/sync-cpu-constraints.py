#!/usr/bin/env python3
"""Pin the packages a profile shares with the cpu image to the deps/cpu/uv.lock versions.

Usage: tools/sync-cpu-constraints.py [--check] <profile>...    (gpu-cu12, rapids-cu12, llm)

--check only reports (exit 1) when a profile's generated block is out of date.

Rewrites the generated block of [tool.uv] constraint-dependencies in
deps/<profile>/pyproject.toml with "name==version" for every registry package the
cpu image installs (base + the dev, core, dl and nlp groups; its spark group adds only
pyspark and py4j, which no other profile installs). Packages that cannot
follow the cpu version are listed with their reason in the profile's own
[tool.dsdl.cpu-constraints] exclude table. uv ignores pins of packages that are not
part of a resolution.

Keeping shared packages identical gives one answer per package and CVE across the
images, and the same behaviour of user notebooks and persisted models.

Order after a cpu lock change:  tools/lock.sh cpu, this script, tools/lock.sh <profile>.
Needs Python 3.11+ (tomllib) or the tomli package.
"""

import pathlib
import re
import sys

try:
    import tomllib
except ModuleNotFoundError:
    import tomli as tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CPU_LOCK = ROOT / "deps" / "cpu" / "uv.lock"
CPU_GROUPS = ("dev", "core", "dl", "nlp")
BEGIN = "  # >>> cpu-lock constraints (generated by tools/sync-cpu-constraints.py, do not edit)\n"
END = "  # <<< cpu-lock constraints\n"


def cpu_closure():
    lock = tomllib.loads(CPU_LOCK.read_text())
    packages = {p["name"]: p for p in lock["package"]}
    root = next(p for p in lock["package"] if "virtual" in p.get("source", {}))
    todo = list(root.get("dependencies", []))
    for group in CPU_GROUPS:
        todo += root.get("dev-dependencies", {}).get(group, [])
    seen = {}
    while todo:
        dep = todo.pop()
        name, extras = dep["name"], set(dep.get("extra", []))
        new_extras = extras - seen.get(name, set())
        if name in seen and not new_extras:
            continue
        seen.setdefault(name, set()).update(extras)
        todo += packages[name].get("dependencies", [])
        for extra in new_extras:
            todo += packages[name].get("optional-dependencies", {}).get(extra, [])
    # path and URL sources (dsdlsupport, en-core-web-sm) are fixed by [tool.uv.sources];
    # the local version label is dropped: "torch==2.14.1" also matches +cpu
    return {name: packages[name]["version"].split("+")[0] for name in seen
            if "registry" in packages[name].get("source", {})}


def sync(profile, pins, check=False):
    pyproject = ROOT / "deps" / profile / "pyproject.toml"
    text = pyproject.read_text()
    exclude = tomllib.loads(text).get("tool", {}).get("dsdl", {}).get("cpu-constraints", {}).get("exclude", {})
    lines = [BEGIN]
    for name in sorted(pins):
        if name in exclude:
            lines.append(f"  # {name}=={pins[name]} not pinned: {exclude[name]}\n")
        else:
            lines.append(f'  "{name}=={pins[name]}",\n')
    lines.append(END)
    pattern = re.compile(re.escape(BEGIN) + ".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        sys.exit(f"{pyproject}: generated constraint block markers not found")
    rendered = pattern.sub(lambda _: "".join(lines), text, count=1)
    if check:
        if rendered != text:
            print(f"{profile}: cpu-lock constraints are out of date; run tools/lock.sh", file=sys.stderr)
            return False
        return True
    pyproject.write_text(rendered)
    excluded = len(exclude.keys() & pins.keys())
    print(f"{profile}: {len(pins) - excluded} pins, {excluded} excluded")
    return True


def main():
    args = sys.argv[1:]
    check = "--check" in args
    profiles = [a for a in args if a != "--check"]
    if not profiles or profiles[0] in ("-h", "--help"):
        sys.exit(__doc__)
    pins = cpu_closure()
    results = [sync(profile, pins, check) for profile in profiles]
    sys.exit(0 if all(results) else 1)


if __name__ == "__main__":
    main()
